const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** URL on `domain` (or any subdomain), optionally followed by a path regex fragment. */
const d = (domain, path = '') => new RegExp(`^https?://(?:[^/?#]*\\.)?${esc(domain)}(?::\\d+)?/${path}`, 'i');

/** npm-style CDN URLs (jsDelivr, unpkg, cdnjs) with a version capture. */
const cdn = (pkg, cdnjsName = pkg) => [
  new RegExp(`(?:/npm/|unpkg\\.com/|esm\\.sh/|skypack\\.dev/)${esc(pkg)}@v?(\\d+\\.\\d+(?:\\.\\d+)?)`, 'i'),
  new RegExp(`/ajax/libs/${esc(cdnjsName)}/(\\d+\\.\\d+(?:\\.\\d+)?)/`, 'i'),
];

