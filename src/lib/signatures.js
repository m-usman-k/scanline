// Offline technology signature database.
//
// Each technology lists one or more rules. Any matching rule marks it as detected; a capture
// group (or a version-like global value) supplies the version.
//
//   probe   dotted global paths read in the page's MAIN world, e.g. 'jQuery.fn.jquery'.
//           An inner array means "all of these must exist" (version comes from the first).
//   special key of a structural probe computed in the page (see lib/probe.js, content/collector.js).
//   url     regexes tested against script, stylesheet and network request URLs.
//   meta    { metaName: regex } tested against <meta name|property|http-equiv> contents.
//   dom     CSS selectors; any match counts.
//   headers { headerName: regex } tested against the main document's response headers.
//   cookies cookie names (string = exact, RegExp = pattern), from document.cookie and Set-Cookie.
//   cssVar  custom properties defined on :root/body.
//   host    regexes tested against the page hostname.
//   notHost regexes; the technology is never reported on matching hostnames.
//   comment regexes tested against HTML comments.
//   ids     key into collected tag IDs (ga4, ua, gtm, aw).
//   implies other technology names that must also be present.
//   tracker privacy classification: analytics | advertising | replay | social | marketing | fingerprinting
//   friendly true for privacy-focused analytics (not counted as trackers).

